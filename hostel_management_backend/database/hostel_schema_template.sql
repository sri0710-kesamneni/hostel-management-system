CREATE TABLE HOSTELS (
  HOSTEL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  HOSTEL_NAME VARCHAR2(100) NOT NULL UNIQUE,
  WARDEN_NAME VARCHAR2(100),
  LOCATION VARCHAR2(150)
);

CREATE TABLE ROOM_TYPES (
  ROOM_TYPE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TYPE_NAME VARCHAR2(50) NOT NULL UNIQUE,
  CAPACITY NUMBER(2) NOT NULL CHECK (CAPACITY > 0),
  FEE NUMBER(10,2) NOT NULL CHECK (FEE >= 0)
);

CREATE TABLE STUDENTS (
  STUDENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  REG_NO VARCHAR2(30) NOT NULL UNIQUE,
  STUDENT_NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(150) NOT NULL UNIQUE,
  PHONE VARCHAR2(20),
  GENDER VARCHAR2(20),
  DEPARTMENT VARCHAR2(100)
);

CREATE TABLE ROOMS (
  ROOM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  HOSTEL_ID NUMBER NOT NULL REFERENCES HOSTELS(HOSTEL_ID),
  ROOM_TYPE_ID NUMBER NOT NULL REFERENCES ROOM_TYPES(ROOM_TYPE_ID),
  ROOM_NUMBER VARCHAR2(20) NOT NULL,
  CAPACITY NUMBER(2) NOT NULL CHECK (CAPACITY > 0),
  OCCUPIED_BEDS NUMBER(2) DEFAULT 0 NOT NULL CHECK (OCCUPIED_BEDS >= 0 AND OCCUPIED_BEDS <= CAPACITY),
  STATUS VARCHAR2(30) NOT NULL CHECK (STATUS IN ('Available','Partially occupied','Full')),
  CONSTRAINT UQ_ROOM_HOSTEL UNIQUE (HOSTEL_ID, ROOM_NUMBER)
);

CREATE TABLE APPLICATIONS (
  APPLICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
  PREFERRED_HOSTEL_ID NUMBER REFERENCES HOSTELS(HOSTEL_ID),
  ROOM_TYPE_ID NUMBER REFERENCES ROOM_TYPES(ROOM_TYPE_ID),
  APPLICATION_DATE DATE DEFAULT SYSDATE NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (STATUS IN ('Pending','Approved','Rejected'))
);

CREATE TABLE ALLOCATIONS (
  ALLOCATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APPLICATION_ID NUMBER NOT NULL UNIQUE REFERENCES APPLICATIONS(APPLICATION_ID),
  STUDENT_ID NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
  ROOM_ID NUMBER NOT NULL REFERENCES ROOMS(ROOM_ID),
  CHECK_IN_DATE DATE NOT NULL,
  CHECK_OUT_DATE DATE,
  STATUS VARCHAR2(20) DEFAULT 'Active' NOT NULL CHECK (STATUS IN ('Active','Pending','Completed')),
  CONSTRAINT CK_ALLOCATION_DATES CHECK (CHECK_OUT_DATE IS NULL OR CHECK_OUT_DATE >= CHECK_IN_DATE)
);

CREATE TABLE PAYMENTS (
  PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
  ALLOCATION_ID NUMBER REFERENCES ALLOCATIONS(ALLOCATION_ID),
  AMOUNT NUMBER(10,2) NOT NULL CHECK (AMOUNT > 0),
  PAYMENT_DATE DATE DEFAULT SYSDATE NOT NULL,
  PAYMENT_METHOD VARCHAR2(30),
  STATUS VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (STATUS IN ('Paid','Pending','Failed'))
);

-- Login table. Password hashes must be generated with BCrypt in a trusted setup script.
CREATE TABLE USERS (
  USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMAIL VARCHAR2(150) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(100) NOT NULL,
  ROLE VARCHAR2(30) DEFAULT 'ADMIN' NOT NULL,
  ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL CHECK (ACTIVE IN ('Y','N'))
);
